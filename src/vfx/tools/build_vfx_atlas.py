#!/usr/bin/env python3
"""Slice the generated VFX source sheets into one packed pixel-art atlas.

Usage: python3 src/vfx/tools/build_vfx_atlas.py
Inputs:  assets/vfx/source/*.jpg (4x2 grids of effects on pure black)
Outputs: assets/vfx/vfx-atlas.png and assets/vfx/vfx-atlas.json
Requires Pillow and numpy.
"""
import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "assets" / "vfx" / "source"
OUT = ROOT / "assets" / "vfx"

# The generator draws chunky pixels roughly 5 source px wide; sampling back
# down to that grid restores crisp pixel art.
DOWNSCALE = 5

SHEETS = [
    {
        "file": "vfx-impacts-source.jpg",
        "mode": "glow",
        "names": [
            "impact.star", "impact.burst", "impact.counter", "impact.block",
            "impact.ring", "impact.guardbreak", "impact.lightning", "impact.flash",
        ],
    },
    {
        "file": "vfx-dust-source.jpg",
        "mode": "solid",
        "names": [
            "dust.step", "dust.kick", "dust.skid", "dust.land",
            "dust.knockdown", "dust.plume", "dust.wisp", "dust.cluster",
        ],
    },
    {
        "file": "vfx-lab-orbs-source.jpg",
        "mode": "glow",
        "names": [
            "lab.openai", "lab.anthropic", "lab.deepmind", "lab.xai",
            "lab.meta", "lab.nvidia", "lab.mistral", "lab.deepseek",
        ],
    },
]


def to_rgba(cell, mode):
    rgb = cell.astype(np.float32) / 255.0
    peak = rgb.max(axis=2)
    if mode == "glow":
        # Brightness on black becomes alpha; unpremultiply so source-over and
        # additive blending both reproduce the original glow.
        alpha = np.clip((peak - 0.06) / 0.94, 0.0, 1.0) ** 0.85
    else:
        alpha = np.clip((peak - 0.08) / 0.22, 0.0, 1.0)
    safe = np.maximum(alpha, 1e-3)[..., None]
    color = rgb / safe if mode == "glow" else rgb
    color = np.clip(color, 0.0, 1.0)
    out = np.dstack([color, alpha])
    out[alpha < 0.04] = 0
    return out


def downsample(rgba):
    h, w = rgba.shape[:2]
    h2, w2 = h // DOWNSCALE, w // DOWNSCALE
    rgba = rgba[: h2 * DOWNSCALE, : w2 * DOWNSCALE]
    blocks = rgba.reshape(h2, DOWNSCALE, w2, DOWNSCALE, 4)
    alpha = blocks[..., 3]
    weight = alpha.sum(axis=(1, 3))
    color = (blocks[..., :3] * alpha[..., None]).sum(axis=(1, 3)) / np.maximum(weight, 1e-6)[..., None]
    a = alpha.mean(axis=(1, 3))
    # Snap alpha to a few hard steps so edges stay pixel-crisp.
    a = np.where(a < 0.1, 0.0, np.where(a < 0.35, 0.4, np.where(a < 0.7, 0.75, 1.0)))
    out = np.dstack([color, a])
    out[a == 0] = 0
    return out


def crop(rgba, pad=1):
    ys, xs = np.nonzero(rgba[..., 3] > 0)
    y0, y1 = max(ys.min() - pad, 0), min(ys.max() + pad + 1, rgba.shape[0])
    x0, x1 = max(xs.min() - pad, 0), min(xs.max() + pad + 1, rgba.shape[1])
    return rgba[y0:y1, x0:x1]


def main():
    sprites = []
    for sheet in SHEETS:
        src = np.asarray(Image.open(SRC / sheet["file"]).convert("RGB"))
        h, w = src.shape[:2]
        cw, ch = w // 4, h // 2
        for i, name in enumerate(sheet["names"]):
            cx, cy = (i % 4) * cw, (i // 4) * ch
            cell = to_rgba(src[cy:cy + ch, cx:cx + cw], sheet["mode"])
            sprites.append((name, sheet["mode"], crop(downsample(cell))))

    # Simple shelf packing, one row per source sheet.
    gap = 2
    rows = [sprites[i:i + 8] for i in range(0, len(sprites), 8)]
    width = max(sum(s[2].shape[1] + gap for s in row) for row in rows) + gap
    height = sum(max(s[2].shape[0] for s in row) + gap for row in rows) + gap
    atlas = np.zeros((height, width, 4), dtype=np.float32)
    frames = {}
    y = gap
    for row in rows:
        x = gap
        row_h = max(s[2].shape[0] for s in row)
        for name, mode, img in row:
            sh, sw = img.shape[:2]
            atlas[y:y + sh, x:x + sw] = img
            frames[name] = {"x": x, "y": y, "w": sw, "h": sh, "blend": "add" if mode == "glow" else "normal"}
            x += sw + gap
        y += row_h + gap

    Image.fromarray((atlas * 255).round().astype(np.uint8), "RGBA").save(OUT / "vfx-atlas.png", optimize=True)
    meta = {
        "image": "vfx-atlas.png",
        "pixelScale": 1,
        "note": "Generated by src/vfx/tools/build_vfx_atlas.py from assets/vfx/source. Frame anchors are centered.",
        "frames": frames,
    }
    (OUT / "vfx-atlas.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"atlas {width}x{height}, {len(frames)} frames")


if __name__ == "__main__":
    main()
